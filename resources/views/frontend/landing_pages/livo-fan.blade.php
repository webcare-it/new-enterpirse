        // Reviews slider
        document.addEventListener('DOMContentLoaded', function() {
            const slider = document.getElementById('reviewSlider');
            const slides = document.querySelectorAll('.review-slide');
            const dotsContainer = document.getElementById('reviewDots');
            const nextButtons = [document.getElementById('reviewNext'), document.getElementById(
                'reviewNextMobile')];
            const prevButtons = [document.getElementById('reviewPrev'), document.getElementById(
                'reviewPrevMobile')];

            let currentIndex = 0;
            let autoPlay;

            function getSlidesPerView() {
                if (window.innerWidth >= 1024) return 3;
                if (window.innerWidth >= 768) return 2;
                return 1;
            }

            function getMaxIndex() {
                return Math.max(0, slides.length - getSlidesPerView());
            }

            function createDots() {
                dotsContainer.innerHTML = '';
                const totalDots = getMaxIndex() + 1;
                for (let i = 0; i < totalDots; i++) {
                    const dot = document.createElement('button');
                    dot.type = 'button';
                    dot.className = 'w-2 h-2 rounded-full bg-gray-300 transition-all duration-300';
                    dot.addEventListener('click', function() {
                        currentIndex = i;
                        updateSlider();
                        restartAutoPlay();
                    });
                    dotsContainer.appendChild(dot);
                }
            }

            function updateDots() {
                const dots = dotsContainer.querySelectorAll('button');
                dots.forEach((dot, index) => {
                    if (index === currentIndex) {
                        dot.classList.remove('bg-gray-300', 'w-2');
                        dot.classList.add('bg-[#0c1117]', 'w-6');
                    } else {
                        dot.classList.remove('bg-[#0c1117]', 'w-6');
                        dot.classList.add('bg-gray-300', 'w-2');
                    }
                });
            }

            function updateSlider() {
                const slidesPerView = getSlidesPerView();
                const percentage = (currentIndex * 100) / slidesPerView;
                slider.style.transform = `translateX(-${percentage}%)`;
                updateDots();
            }

            function nextSlide() {
                const maxIndex = getMaxIndex();
                currentIndex = currentIndex >= maxIndex ? 0 : currentIndex + 1;
                updateSlider();
            }

            function previousSlide() {
                const maxIndex = getMaxIndex();
                currentIndex = currentIndex <= 0 ? maxIndex : currentIndex - 1;
                updateSlider();
            }

            nextButtons.forEach(btn => {
                if (btn) btn.addEventListener('click', () => {
                    nextSlide();
                    restartAutoPlay();
                });
            });
            prevButtons.forEach(btn => {
                if (btn) btn.addEventListener('click', () => {
                    previousSlide();
                    restartAutoPlay();
                });
            });

            function startAutoPlay() {
                autoPlay = setInterval(nextSlide, 4200);
            }

            function stopAutoPlay() {
                clearInterval(autoPlay);
            }

            function restartAutoPlay() {
                stopAutoPlay();
                startAutoPlay();
            }

            slider.addEventListener('mouseenter', stopAutoPlay);
            slider.addEventListener('mouseleave', startAutoPlay);

            window.addEventListener('resize', function() {
                if (currentIndex > getMaxIndex()) currentIndex = getMaxIndex();
                createDots();
                updateSlider();
            });

            let touchStartX = 0;
            slider.addEventListener('touchstart', e => {
                touchStartX = e.changedTouches[0].screenX;
                stopAutoPlay();
            }, {
                passive: true
            });
            slider.addEventListener('touchend', e => {
                const diff = touchStartX - e.changedTouches[0].screenX;
                if (Math.abs(diff) > 50) {
                    if (diff > 0) nextSlide();
                    else previousSlide();
                }
                startAutoPlay();
            }, {
                passive: true
            });

            createDots();
            updateSlider();
            startAutoPlay();
        });
    </script>

